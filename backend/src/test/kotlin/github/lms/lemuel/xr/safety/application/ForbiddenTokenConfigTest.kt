/**
 * 저작 YAML(`content/{인물}/scene*.yml`)의 `lint_forbidden_tokens` 가 실제로
 * 런타임 설정에 반영돼 있는지 검증한다.
 *
 * 이 테스트의 존재 이유: 이 목록은 오랫동안 저작 파일에만 있었고 어떤 코드도 읽지 않았다.
 * "설정에 적혀 있다"와 "빈으로 주입돼 동작한다" 사이가 벌어지면 게이트는 다시 주석이 된다.
 * content/ 는 백엔드 클래스패스가 아니므로 자동 동기화가 안 된다 — 그래서 대표 토큰이
 * 빠지면 여기서 깨지게 해 둔다.
 *
 * ⚠️ 케이스 작성 규칙 — 이 테스트 자신이 vacuous green 이 되지 않도록:
 * 초기 케이스는 전부 *토큰 문자열이 그대로 박힌 형태*("정신 차려요" ← 토큰 "정신 차려")로
 * 쓰여 있었다. 그러면 검증되는 것은 위반 공간이 아니라 토큰 문자열 자기 자신이다 — 실제
 * LLM 은 "정신 차리세요" 라고 쓰고, 그건 통과했다(실측 15종 중 6종이 활용/높임 변경만으로 뚫림).
 * **위반 축 하나당 최소 두 형태를 넣는다 — (a) 사전형, (b) LLM 이 실제로 쓸 높임·활용형.**
 *
 * ⚠️ mustPass 에도 같은 규칙이 적용된다 — 오히려 여기가 더 새기 쉽다:
 * **각 문장은 "그 토큰이 잡을 뻔한 가장 자연스러운 위로" 여야 한다.** 우회 표면을 고르면 안 된다.
 * 실패 사례를 남긴다 — 토큰이 `게을러서 그` 인데 케이스를 "게을러서가 아니라…" 로,
 * 토큰이 `바르게 살아` 인데 "바르게 살지 못했다고…" 로 골랐던 적이 있다. 둘 다 축을 우연히
 * 비껴가서 초록이었을 뿐, 진짜 자연스러운 위로("게을러서 그런 게 아닙니다",
 * "바르게 살아야 한다고 말하지 않겠습니다")는 그때 실제로 차단되고 있었다.
 * 케이스를 추가할 때는 *토큰을 보고 문장을 고르지 말고*, 그 축에서 사목적으로 가장 하고 싶은
 * 말을 먼저 쓴 다음 걸리는지 확인하라.
 *
 * 한국어 형태론 규칙(위 실패의 근본 원인): 부정은 언제나 어간·어근 *뒤* 에
 * `-지 않/못` 또는 `-가 아니` 로 붙는다. 따라서 **어간에서 끊은 토큰은 그 축의 부정형 위로를
 * 반드시 삼킨다.**
 *
 * 2026-08-04 — 이 문제는 이제 토큰이 아니라 스캐너에서 다룬다. 토큰마다 명령형 어미를 붙여
 * 좁히는 길은 *좁은 토큰이 활용만으로 뚫리는* 반대편 실패를 부른다(솔로몬
 * `이제 깨달았으니` → `깨달았으`). [ForbiddenTokenScanner.CONCESSIVE_NEGATION] 이
 * `-지 않아도`·`-지 못해도` 를 목록 전 종에 대해 한 번에 면제한다. 아래 mustPass 의
 * `양보 부정` 묶음이 그 면제가 살아 있는지 고정하고, `의도적 과차단` 테스트가 면제가
 * `-가 아니` 계열까지 번지지 않았는지 고정한다.
 */
