            "마음을 다잡으실 때가 되었습니다.",              // ≈ 정신 차려
            // 욥 R3 도 예외가 아니다. 토큰 32종을 새로 넣었지만 축은 여전히 안 막힌다 —
            // 막은 것은 "갑절/배/곱절/믿음의 크기" 라는 *표층 어휘* 지 보상 신학이 아니다.
