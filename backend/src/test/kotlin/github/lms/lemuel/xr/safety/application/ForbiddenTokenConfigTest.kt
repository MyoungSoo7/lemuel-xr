package github.lms.lemuel.xr.safety.application

import github.lms.lemuel.xr.IntegrationTestBase
import org.assertj.core.api.Assertions.assertThat
import org.junit.jupiter.api.Test
import org.springframework.beans.factory.annotation.Autowired

/**
 * 저작 YAML(`content/{인물}/scene*.yml`)의 `lint_forbidden_tokens` 가 실제로
 * 런타임 설정에 반영돼 있는지 검증한다.
 *
 * 이 테스트의 존재 이유: 이 목록은 오랫동안 저작 파일에만 있었고 어떤 코드도 읽지 않았다.
 * "설정에 적혀 있다"와 "빈으로 주입돼 동작한다" 사이가 벌어지면 게이트는 다시 주석이 된다.
 * content/ 는 백엔드 클래스패스가 아니므로 자동 동기화가 안 된다 — 그래서 대표 토큰이
 * 빠지면 여기서 깨지게 해 둔다.
 *
 * ⚠️ 케이스 작성 규칙 — 이 테스트 자신이 vacuous green 이 되지 않도록:
 * 초기 케이스는 전부 *토큰 문자열이 그대로 박힌 형태*("정신 차려요" ← 토큰 "정신 차려")로
 * 쓰여 있었다. 그러면 검증되는 것은 위반 공간이 아니라 토큰 문자열 자기 자신이다 — 실제
 * LLM 은 "정신 차리세요" 라고 쓰고, 그건 통과했다(실측 15종 중 6종이 활용/높임 변경만으로 뚫림).
 * **위반 축 하나당 최소 두 형태를 넣는다 — (a) 사전형, (b) LLM 이 실제로 쓸 높임·활용형.**
 *
 * ⚠️ mustPass 에도 같은 규칙이 적용된다 — 오히려 여기가 더 새기 쉽다:
 * **각 문장은 "그 토큰이 잡을 뻔한 가장 자연스러운 위로" 여야 한다.** 우회 표면을 고르면 안 된다.
 * 실패 사례를 남긴다 — 토큰이 `게을러서 그` 인데 케이스를 "게을러서가 아니라…" 로,
 * 토큰이 `바르게 살아` 인데 "바르게 살지 못했다고…" 로 골랐던 적이 있다. 둘 다 축을 우연히
 * 비껴가서 초록이었을 뿐, 진짜 자연스러운 위로("게을러서 그런 게 아닙니다",
 * "바르게 살아야 한다고 말하지 않겠습니다")는 그때 실제로 차단되고 있었다.
 * 케이스를 추가할 때는 *토큰을 보고 문장을 고르지 말고*, 그 축에서 사목적으로 가장 하고 싶은
 * 말을 먼저 쓴 다음 걸리는지 확인하라.
 *
 * 한국어 형태론 규칙(위 실패의 근본 원인): 부정은 언제나 어간·어근 *뒤* 에
 * `-지 않/못` 또는 `-가 아니` 로 붙는다. 따라서 **어간에서 끊은 토큰은 그 축의 부정형 위로를
 * 반드시 삼킨다.**
 *
 * 2026-08-04 — 이 문제는 이제 토큰이 아니라 스캐너에서 다룬다. 토큰마다 명령형 어미를 붙여
 * 좁히는 길은 *좁은 토큰이 활용만으로 뚫리는* 반대편 실패를 부른다(솔로몬
 * `이제 깨달았으니` → `깨달았으`). [ForbiddenTokenScanner.CONCESSIVE_NEGATION] 이
 * `-지 않아도`·`-지 못해도` 를 543종 전부에 대해 한 번에 면제한다. 아래 mustPass 의
 * `양보 부정` 묶음이 그 면제가 살아 있는지 고정하고, `의도적 과차단` 테스트가 면제가
 * `-가 아니` 계열까지 번지지 않았는지 고정한다.
 */
class ForbiddenTokenConfigTest : IntegrationTestBase() {

    @Autowired
    private lateinit var scanner: ForbiddenTokenScanner

    @Test
    fun `스캐너가 스프링 빈으로 등록돼 있다`() {
        assertThat(scanner).isNotNull()
    }

    @Test
    fun `저작 규칙의 대표 가스라이팅 토큰이 런타임에 살아 있다`() {
        // 각 인물 시나리오의 핵심 금지 표현. 하나라도 빠지면 그 시나리오의
        // 안전 규칙이 런타임에서 무력화된 것이다.
        val mustBlock = listOf(
            "믿음이 부족해서 그렇습니다",       // 공통 — 책임 전가
            "빨리 회복하셔야죠",                // 공통 — 회복 압박
            "다시 일어나 싸워야 합니다",         // 엘리야 — 탈진 상태에 투쟁 요구
            "정신 차려요",                      // 엘리야 — 질책
            "허무를 극복하세요",                // 솔로몬 — 실존적 공허를 결함 취급
            "욕심이 많아서 그래요",             // 솔로몬 — 비난
            "사역으로 돌아가세요",              // 엘리야 — 역할 복귀 압박
            // 아래 4건은 오랫동안 *축만 선언되고 토큰이 0종* 이던 게이트를 채우며 추가됐다
            // (elijah scene2/3/5 · solomon scene5). 문장이 하나라도 통과하면 그 게이트는
            // 다시 통과 로그만 남기는 빈 게이트로 돌아간 것이다.
            "당신이 무너진 건 믿음이 약해서입니다.",  // 엘리야 S2 R2 — 무너짐을 사용자 결함으로 귀속
            "이제 그만 쉬고 일어나세요.",            // 엘리야 S3 R3 — 쉼 중단 재촉
            "하나님이 당신을 도구로 다시 쓰신다는 뜻입니다.", // 엘리야 S5 R3 — 사람의 도구화
            "허무를 느꼈으니 이제 바르게 살아라.",     // 솔로몬 S5 R3 — 공허의 교훈화
            // /새인물 초안 5인(아브라함·다니엘·에스더·야곱·베드로). 이 인물들의 축은 아직
            // 사람 사인오프 전이지만, 토큰이 런타임에 *반영됐는지* 는 지금 고정해 둔다.
            "조금만 더 기다리면 반드시 이루어집니다.",   // 아브라함 — 기다림 도구화 + 응답 보증
            "고난에는 뜻이 있으니 담대해지세요.",        // 다니엘 — 고난 의미부여 + 태도 요구
            "당신이 이 자리에 있는 이유가 있습니다.",     // 에스더 — 위치의 섭리화("있는 데는 이유가")
            "이제는 먼저 연락해서 용서해야 합니다.",      // 야곱 — 화해 시점을 피해자에게 강요
            "하나님이 당신을 겸손하게 하시려고 실패를 주신 겁니다.", // 베드로 — 실패의 교육적 도구화
        )

        val leaked = mustBlock.filterNot { scanner.scan(it).matched }

        assertThat(leaked)
            .describedAs("이 문장들이 게이트를 통과했다 — 금지 토큰 설정이 누락됐다")
            .isEmpty()
    }

    @Test
    fun `같은 위반을 높임 활용형으로 바꿔도 막힌다 — 토큰 자기검증 방지`() {
        // 위 테스트의 각 축과 *같은 위반* 을, LLM 이 실제로 생성할 법한 높임·활용형으로 다시 쓴다.
        // 한글은 존칭 '-시-'가 다음 음절에 합쳐지고(깨달았으니→깨달으셨으니) 어간이 교체돼
        // (싸워→싸우, 차려→차리, 이겨→이기) 부분문자열 토큰이 활용만으로 뚫린다.
        // 여기 한 줄이라도 통과하면, 게이트는 "우리가 예시로 쓴 문장" 만 막고 있는 것이다.
        val mustBlock = listOf(
            "정신 차리세요.",                         // ← "정신 차려" 로는 안 잡힘
            "이제 다시 싸우세요.",                     // ← "이제 다시 싸워"
            "다시 일어나 싸우셔야 합니다.",             // ← "다시 일어나 싸워"
            "이제 그만하고 싸우십시오.",
            "다시 이기세요.",                         // ← "다시 이겨"
            "반드시 이기셔야 합니다.",
            "욕심이 많으셔서 그런 겁니다.",             // ← "욕심이 많아서"
            "늘 욕심이 많으시니 채워지지 않는 겁니다.",
            "이제 깨달으셨으니 달라지셔야죠.",          // ← "이제 깨달았으니"
            "깨달았으니 이제 행동으로 옮기세요.",
            "당신 때문에 이 일이 벌어진 겁니다.",       // ← "너 때문" 만으로는 안 잡힘
            // 삭제한 토큰의 커버리지가 유지되는지 고정한다.
            // '이제 깨달았으니' → '깨달았으' 로 대체, '깨달았으면' → 삭제(포섭).
            "이제 깨달았으니 달라지셔야죠.",
            "허무를 깨달았으면 이제 바꾸세요.",
            // 초안 5인의 같은 축을, 어간형이 아니라 LLM 이 실제로 쓸 높임·활용형으로 다시.
            "조금만 더 기다리시면 됩니다.",              // 아브라함 — "조금만 더 기다리" 어간 뒤 높임
            "타협하지 마시고 담대해지십시오.",            // 다니엘 — "타협하지 마" + "담대해지십"
            "당신만이 할 수 있는 일입니다.",              // 에스더 — "만이 할 수 있"
            "관계는 회복되어야죠.",                      // 야곱 — "관계는 회복되어야죠"
            "더 키우시려고 넘어뜨리신 겁니다.",           // 베드로 — "더 키우시려"
        )

        val leaked = mustBlock.filterNot { scanner.scan(it).matched }

        assertThat(leaked)
            .describedAs("이 문장들이 게이트를 통과했다 — 금지 토큰 설정이 누락됐다")
            .isEmpty()
    }

    @Test
    fun `정상적인 위로 문장은 차단하지 않는다`() {
        // 과차단(false positive)은 콘텐츠를 망가뜨린다. 게이트가 지나치게 넓지 않은지 확인.
        val mustPass = listOf(
            "오늘 버텨낸 것만으로 충분합니다.",
            "하나님은 책망보다 떡과 잠을 먼저 주셨습니다.",
            "지금 쉬어도 괜찮습니다.",
            "당신의 슬픔에는 이유가 있습니다.",
            // 새 토큰이 *부정형 위로* 까지 삼키지 않는지 — 여기 걸리면 사용자는 위로 대신
            // fallback-text 만 받게 된다. 과차단은 안전이 아니라 손실이다.
            "믿음이 약해도 괜찮습니다. 무너짐은 실패가 아닙니다.",
            "게을러서가 아니라 정말로 지치신 겁니다.",
            "당신은 하나님의 도구가 아니라 자녀입니다.",
            "바르게 살지 못했다고 자책하지 않으셔도 됩니다.",
            "쓸모없다고 느껴지는 날이 있습니다. 그 느낌도 정직한 감정입니다.",
            // 명령형 어미를 토큰으로 쓰고 어간형('다시 싸우')을 피한 이유가 이 네 줄이다.
            // 엘리야 Scene 5 의 신학 비트가 바로 "혼자 싸우지 않아도 된다" 이므로,
            // 어간형 토큰은 이 앱이 하려는 말 자체를 차단한다.
            "이제 다시 싸우지 않으셔도 됩니다.",
            "일어나 싸우지 않아도 괜찮습니다.",
            "다시 이기려 애쓰지 않으셔도 됩니다.",
            "혼자 싸우지 않게 하시려고 엘리사를 곁에 주셨습니다.",
            "당신 때문이 아닙니다.",
            // 아래는 코디네이터가 실측한 오차단 9건 중 *좁혀서 통과시킨* 6건이다.
            // 전부 "그 토큰이 잡을 뻔한 가장 자연스러운 위로" — 우회 표면이 아니다.
            "하나님은 당신을 도구로 쓰지 않으십니다.",
            "하나님은 당신을 도구로 삼지 않으십니다.",
            "이 공허를 교훈으로 삼지 않으셔도 됩니다.",
            "쓰임받지 못해도 괜찮습니다.",
            "정신 차리지 않아도 됩니다.",
            "정신 차리라고 말하지 않겠습니다.",
            "바르게 살아야 한다고 말하지 않겠습니다.",
            // 초안 5인 — 각 축에서 *사목적으로 가장 하고 싶은 말* 을 먼저 쓰고 걸리는지 봤다.
            // 여기 하나라도 걸리면 그 인물의 토큰이 이 앱이 하려는 말 자체를 삼킨 것이다.
            "언제 응답될지 저도 모릅니다. 모르는 채로 함께 있겠습니다.", // 아브라함 — 기한 보증 없는 동행
            "기다리다 지치셨다면 그만 기다려도 괜찮습니다.",             // 아브라함 — "조금만 더 기다리" 의 부정형
            "물러서도 괜찮습니다. 그건 배신이 아닙니다.",                // 다니엘 — "물러서지 마" 의 부정형
            "담대해지지 않아도 됩니다. 무서운 게 정상입니다.",           // 다니엘 — 태도 요구의 해제
            "말하지 않기로 한 선택도 존중받아야 합니다.",                // 에스더 — "말해야 합니다" 의 부정형
            "숨어 있는 지금도 비겁한 게 아닙니다.",                      // 에스더 — "숨는 건 비겁" 의 부정형
            "용서하지 않으셔도 됩니다. 아직 안 해도 됩니다.",            // 야곱 — "용서해야" 의 부정형
            "먼저 연락하지 않아도 괜찮습니다.",                          // 야곱 — "먼저 연락해" 의 부정형
            "다시는 그러지 않겠다고 다짐하지 않으셔도 됩니다.",          // 베드로 — 재다짐 압박의 해제
            "실패가 당신을 설명하지 않습니다.",                          // 베드로 — "실패했으니" 의 부정형
            // --- 양보 부정 면제 (2026-08-04) ---
            // 어간에서 끊은 토큰이 그 축의 정당한 위로까지 삼키던 실측 사례들.
            // 여기 하나라도 막히면 [ForbiddenTokenScanner.CONCESSIVE_NEGATION] 이 죽은 것이다.
            "빨리 회복하지 않아도 됩니다.",             // ← "빨리 회복" (엘리야 S5 R3 의 핵심 문장)
            "빨리 회복되지 않아도 괜찮습니다.",
            "사역으로 돌아가지 않아도 괜찮습니다.",      // ← "사역으로 돌아가"
            "허무를 극복하지 않아도 괜찮습니다.",        // ← "허무를 극복" (솔로몬)
            "믿음이 부족하지 않아도 괜찮습니다.",        // ← "믿음이 부족"
        )

        val blocked = mustPass.filter { scanner.scan(it).matched }

        assertThat(blocked)
            .describedAs("정상 문장이 차단됐다 — 토큰이 지나치게 넓다")
            .isEmpty()
    }

    @Test
    fun `의도적 과차단 — 부정으로 꺼내는 수치 프레임도 막는다`() {
        // 코디네이터 실측 9건 중 나머지 3건 + 인접 2건. 이건 결함이 아니라 *결정* 이다.
        //
        // 좁힐 수는 있다("믿음이 약해서입" 처럼 긍정 계속형을 붙이면 부정형과 갈라진다).
        // 좁히지 않은 이유: 부정으로 꺼내는 프레임도 프레임이다. "믿음이 약해서가 아닙니다" 는
        // 사용자가 갖고 있지도 않았을 수 있는 '네 믿음이 약하다' 는 종교적 수치 프레임을
        // 앱이 먼저 꺼내서 부정하는 문장이고, 우울·종교적 트라우마 상태의 독자에게는
        // 그 프레임을 *심는* 쪽으로 작동한다. 도구화·교훈화 축(위 mustPass)과 다른 점은,
        // 그쪽은 프레임이 이미 교회 문화에서 사용자 머릿속에 있어 부정이 치료적이라는 것이다.
        //
        // 이 결정의 대가는 아래 `대안 표면` 테스트가 지불한다 — 같은 뜻을 말할 길이 반드시
        // 열려 있어야 하고, 없다면 이 결정은 철회돼야 한다.
        val intentionallyBlocked = listOf(
            "믿음이 약해서가 아닙니다.",
            "의지가 약해서가 아닙니다.",
            "기도가 부족해서가 아닙니다.",
            "게을러서 그런 게 아닙니다.",
            "약해서 무너진 게 아닙니다.",
        )

        val leaked = intentionallyBlocked.filterNot { scanner.scan(it).matched }

        assertThat(leaked)
            .describedAs(
                "의도적으로 막기로 한 문장이 통과했다. 토큰을 좁혔다면 그 결정을 여기 주석과 " +
                    "content/elijah/scene2·scene3 의 '의도적 과차단' 주석에서 함께 지울 것.",
            )
            .isEmpty()
    }

    @Test
    fun `의도적 과차단의 대가 — 같은 뜻을 말할 대안 표면이 반드시 열려 있다`() {
        // 위 테스트가 막은 다섯 축 각각에 대해, 사목적으로 같은 말을 하는 통과 경로가 있는가.
        // 하나라도 막히면 그 축은 '위로 자체가 불가능한 축' 이 되고, 그건 안전이 아니라 검열이다.
        val mustHaveAnAlternative = listOf(
            "믿음이 약해도 괜찮습니다.",              // ← 믿음이 약해서
            "무너짐은 믿음의 실패가 아닙니다.",         // ← 약해서 무너
            "의지의 문제가 아닙니다.",                // ← 의지가 약해서
            "기도의 양이 원인이 아닙니다.",            // ← 기도가 부족해서
            "게을러서가 아니라 정말로 지치신 겁니다.",   // ← 게을러서 그
            "게으름이 아니라 소진입니다.",
        )

        val blocked = mustHaveAnAlternative.filter { scanner.scan(it).matched }

        assertThat(blocked)
            .describedAs("의도적 과차단 축의 *대안 표면* 까지 막혔다 — 이제 그 축은 위로가 불가능하다. 토큰을 좁혀라.")
            .isEmpty()
    }

    @Test
    fun `알려진 한계 — 유의어 재작성은 이 게이트로 막지 못한다`() {
        // 정직성 장치다. 부분문자열 lint 가 막는 것은 *알려진 표층형의 재발* 이지 의미가 아니다.
        // 아래는 전부 위 mustBlock 과 같은 위반인데 어휘를 바꾼 것뿐이고, 전부 통과한다.
        // 이 목록을 남겨 두는 이유: "토큰을 늘려서 막았다" 는 착각을 코드로 반증하기 위해서다.
        // 실제 방어선은 (a) LLM 시스템 프롬프트 제약, (b) 사람 안전 검토다.
        val knownBypass = listOf(
            "감사할 줄 모르셔서 이런 일이 오신 겁니다.",     // ≈ 감사가 부족
            "믿음이 여전히 모자라셨던 것 같습니다.",         // ≈ 믿음이 부족
            "허무함을 이겨내셔야 합니다.",                  // ≈ 허무를 극복
            "이제 사역 자리로 돌아오셔야 하지 않겠어요?",     // ≈ 사역으로 돌아가
            "마음을 다잡으실 때가 되었습니다.",              // ≈ 정신 차려
        )

        val caught = knownBypass.filter { scanner.scan(it).matched }

        assertThat(caught)
            .describedAs(
                "유의어 문장이 잡히기 시작했다. 좋은 일이지만, 이 목록은 '못 막는다' 는 " +
                    "사실을 기록하는 곳이다 — 잡히게 된 문장은 여기서 빼고 mustBlock 으로 옮길 것. " +
                    "동시에 그 토큰이 정당한 표현을 과차단하지 않는지 반드시 재검토할 것.",
            )
            .isEmpty()
    }
