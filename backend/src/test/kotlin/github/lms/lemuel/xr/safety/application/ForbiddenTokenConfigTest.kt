    @Test
    fun `의도적 과차단 — 부정으로 꺼내는 수치 프레임도 막는다`() {
        // 코디네이터 실측 9건 중 나머지 3건 + 인접 2건. 이건 결함이 아니라 *결정* 이다.
        //
        // 좁힐 수는 있다("믿음이 약해서입" 처럼 긍정 계속형을 붙이면 부정형과 갈라진다).
        // 좁히지 않은 이유: 부정으로 꺼내는 프레임도 프레임이다. "믿음이 약해서가 아닙니다" 는
        // 사용자가 갖고 있지도 않았을 수 있는 '네 믿음이 약하다' 는 종교적 수치 프레임을
        // 앱이 먼저 꺼내서 부정하는 문장이고, 우울·종교적 트라우마 상태의 독자에게는
        // 그 프레임을 *심는* 쪽으로 작동한다. 도구화·교훈화 축(위 mustPass)과 다른 점은,
        // 그쪽은 프레임이 이미 교회 문화에서 사용자 머릿속에 있어 부정이 치료적이라는 것이다.
        //
        // 이 결정의 대가는 아래 `대안 표면` 테스트가 지불한다 — 같은 뜻을 말할 길이 반드시
        // 열려 있어야 하고, 없다면 이 결정은 철회돼야 한다.
        val intentionallyBlocked = listOf(
            "믿음이 약해서가 아닙니다.",
            "의지가 약해서가 아닙니다.",
            "기도가 부족해서가 아닙니다.",
            "게을러서 그런 게 아닙니다.",
            "약해서 무너진 게 아닙니다.",
        )

        val leaked = intentionallyBlocked.filterNot { scanner.scan(it).matched }

        assertThat(leaked)
            .describedAs(
                "의도적으로 막기로 한 문장이 통과했다. 토큰을 좁혔다면 그 결정을 여기 주석과 " +
                    "content/elijah/scene2·scene3 의 '의도적 과차단' 주석에서 함께 지울 것.",
            )
            .isEmpty()
    }

