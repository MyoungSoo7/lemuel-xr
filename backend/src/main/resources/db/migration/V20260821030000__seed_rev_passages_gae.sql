-- 확인 — rev 가 modern 과 같은 참조 집합을 덮는가.
DO $$
DECLARE
    n_modern INT;
    n_rev    INT;
    n_gap    INT;
BEGIN
    SELECT count(*) INTO n_modern FROM scripture_passages WHERE translation = 'modern';
    SELECT count(*) INTO n_rev    FROM scripture_passages WHERE translation = 'rev';
    SELECT count(*) INTO n_gap FROM scripture_passages m
     WHERE m.translation = 'modern'
       AND NOT EXISTS (SELECT 1 FROM scripture_passages r
                        WHERE r.translation = 'rev' AND r.reference = m.reference);
    RAISE NOTICE 'scripture_passages: modern=% rev=% rev 가 못 덮는 참조=%',
        n_modern, n_rev, n_gap;
    IF n_gap > 0 THEN
        RAISE EXCEPTION '기본 번역본을 rev 로 옮기면 참조 %건이 404 가 된다 (백엔드에 폴백 없음)', n_gap;
    END IF;
END $$;
