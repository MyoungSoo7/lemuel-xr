-- 두 역본을 섞어 읽히는 것은 미션 4편 전부다.
--
-- 이건 새 결정이 아니라 **예고된 swap 의 실행** 이다:
--   · `V1__init_schema.sql:46`  translation VARCHAR(20) -- 'modern' | 'rev' (개역개정 fallback)
--   · `V20260717073355:12`      "공개 출시 전 개역개정으로 swap — translation='rev' 로 분리 예정"
--   · `V20260820051500:37`      "translation='modern' 으로 분리해 두어 추후 'rev' 로 swap 가능하게 한다"
--   · `docs/CONTENT-WORKFLOW.md:477`     "MVP 는 개역개정 우선"
--   · `docs/BACKEND-ARCHITECTURE.md:847` 위험 #4 — 현대인의 성경은 라이선스 분쟁 항목,
--                                        완화책이 "개역개정 fallback"
--
-- ## 무엇을
--
-- `modern` 92행을 **지우지 않는다.** 같은 `reference` 에 `translation='rev'` 행을 더
