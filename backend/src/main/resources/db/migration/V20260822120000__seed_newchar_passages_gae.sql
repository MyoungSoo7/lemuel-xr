-- ## 왜
--
-- 이 다섯 인물은 `content/{인물}/scene*.yml` 저작이 끝나 있는데도 런타임에 없었다.
-- 런타임에 올리면 시나리오 yml 이 `scripture_ref` 를 적게 되고, 그 키는
-- `scripture_passages.reference` 와 정확 일치로 조회된다
-- (`findFirstByReferenceAndTranslation`). 지금 시드에 있는 60개 키는 전부 기존 8인물
-- 것이고, 이 다섯 인물이 인용하는 110개 절은 **한 행도 없다.**
-- 행이 없으면 미션 화면의 본문 블록이 조용히 비어서 뜬다 — 예외도 404 도 안 난다.
--
-- ## 무엇을
--
-- `content/{인물}/scene*.yml` 의 `text_ko` 에 **실제로 인용된 절만** 넣는다.
-- 인용되지 않은 절은 한 행도 넣지 않는다 — 특히 각 미션이 명시적으로 배제한 구절
-- (예: `docs/MVP-PETER.md` disputed_points 5번의 범위 밖 후속 절)은 애초에 수집
-- 대상에 들어오지 않는다. 수집기는 인용 목록에서 키를 만들지, 장 전체를 붓지 않는다.
--
-- 역본은 `rev`(개역개정) 하나만 넣는다. `modern`(KLB) 행은 만들지 않는다 —
-- 런타임 기본값이 이미 `rev` 이고(V20260821030000), KLB 는 라이선스 위험 항목이라
-- 새 인물을 그쪽으로 늘리지 않는다.
--
