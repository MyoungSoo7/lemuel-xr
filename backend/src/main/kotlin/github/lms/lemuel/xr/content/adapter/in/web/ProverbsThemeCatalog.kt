 *
 * DB 시드 대신 코드 상수 — 잠언 본문은 immutable 하고, 주제 분류는 콘텐츠가 아니라
 * UI 분류 축이므로 마이그레이션(주제 시드 테이블) 불필요. 기존 카드 seed(prov-3:5 · prov-10:19 ·
 * prov-4:23 · prov-29:25)와 ref 규칙(prov-{장}:{절})을 공유한다.
 *
 * 톤 (R2/R3): 잠언의 단순화 위험(§3.4 — "노력하면 된다" 류가 지친 사용자에게 역효과)을
 * 피하기 위해, 각 주제에 "지혜는 결과 보장이 아니라 방향"이라는 안내(guidance)를 함께 둔다.
