/**
 * 기준2 (잠언과 지혜) — 잠언 지혜를 카테고리(주제)로 분류한 정적 카탈로그.
 *
 * TRACK-A-1-4-WISDOM-EMOTION §3 (Theme 2). [EcclesiastesCatalog] 스타일 —
 * 주제 상수 + 각 주제에 실존 잠언 구절 매핑. GET /api/content/proverbs/by-theme?theme=... 로 조회.
 *
 * 근거는 잠언(성경)만 — 각 주제의 ref·verse 는 실제 잠언 본문뿐.
