package github.lms.lemuel.xr.tts.application.port.out

/**
 * 합성 작업을 백그라운드로 넘기는 아웃바운드 포트.
 *
 * 왜 큐가 *유계(bounded)* 여야 하는가 — 실측 근거:
 * CPU-only Coqui XTTS-v2 의 실시간 계수(RTF)는 오디오 1초당 CPU 4.1~4.6초다.
 * 즉 워커 하나가 문장 하나에 수십 초~수 분을 붙잡는다. 큐가 무제한이면 요청이
 * 쌓이는 만큼 대기시간이 선형으로 늘어, 뒤에 선 사용자는 영원히 못 받으면서
 * 서버는 "정상" 으로 보인다. 차라리 즉시 429 로 거절하고 Retry-After 를 주는 편이
 * 사용자에게 정직하다.
 */
interface TtsJobQueuePort {

    /**
     * 작업을 큐에 넣는다.
     *
     * @return 큐가 가득 차 받지 못했으면 false. 호출자는 이때 429 로 응답해야 한다.
     */
    fun submit(jobId: String, task: () -> Unit): Boolean

    /** 대기 중인 작업 수 — Retry-After 를 추정하는 데 쓴다. */
    fun queueDepth(): Int

    /**
     * 이 프로세스가 [jobId] 를 실제로 들고 있는가 — 큐에서 대기 중이거나 워커가 합성 중.
     *
     * **고아 작업을 가려내는 유일한 수단이다.** 진행 상태는 DB 행(PENDING)에 남지만 큐와
     * 워커는 JVM 안에만 있다. 그래서 배포·OOM·강제종료로 프로세스가 갈리면 *아무도 처리하지
     * 않는데 행만 PENDING 인* 유령이 남는다. 그 행을 그대로 믿으면 같은 문장을 다시 요청해도
     * "이미 진행 중" 이라며 큐에 넣지 않아 **영원히 소리가 나지 않는다** (실제로 그랬다).
     *
     * "DB 는 PENDING 인데 이 프로세스는 모른다" 가 곧 "고아다" 라는 판정은 **replicas 가
     * 1일 때만 정확하다.** 2 이상으로 올리려면 이 판정을 프로세스 밖(공유 큐 또는 작업
     * 소유권 클레임)으로 옮겨야 한다 — 안 그러면 B 파드가 A 파드의 진행 중 작업을 고아로
     * 오인해 중복 합성한다. 사이드카가 1개라 replicas 를 올릴 이유가 지금은 없다.
     *
     * 시간 기반(오래된 PENDING = 고아)으로 하지 않은 이유: 정상 대기 시간이 큐 깊이에 따라
     * 수 초에서 수십 분까지 벌어져 임계값을 정직하게 고를 수 없다. 소유 여부는 추측이 아니다.
     */
    fun isInFlight(jobId: String): Boolean
}
