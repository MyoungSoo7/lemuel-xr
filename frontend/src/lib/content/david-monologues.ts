/**
 * 다윗 미션의 *정적* 모놀로그 / 아웃컴 텍스트.
 *
 * 요셉·모세와 동일한 *frontend 직결* 형식 (`moses-monologues.ts` 참조). backend 는
 * david.yml 의 `monologue_cache_keys` 만 갖고 있고 `monologues/outcomes/reactions`
 * map 은 없으므로 `DecideSceneUseCase.matchResponseText` 는 david 에서 null 을 반환한다.
 * 따라서 각 결정의 echo 텍스트는 *frontend fallback* (본 파일) 이 담당한다.
 * 자문 통과 후 backend round-trip + LLM 으로 shape 유지한 채 교체 가능.
 *
 * shape: `<scene><decision> : Monologue`.
 *
 * `Monologue` 는 *산문 + 인용 위치* 의 배열이다 — 성경 자구는 이 파일에 없고
 * `/api/scripture` 응답에서 온다(`scripture-quote.ts` 머리말).
 *
 * ─────────────────────────────────────────────────────────────
 * 신학 기준 — 합신(개혁주의/웨스트민스터) + 성경만 근거.
 *  - 골리앗 승리는 *하나님의 주권* 과 *다윗의 나아감* 이 함께 있는 사건이다
 *    (WCF 5.2~5.3, concurrence/섭리적 협력). "전쟁은 여호와께 속한 것"(삼상 17:47)
 *    이 근거이며, 다윗의 물맷돌은 하나님이 쓰신 *2차 원인(second cause)* 이다.
 *  - 승리를 다윗의 용기·기술의 결과로만 돌리지 않는다(펠라기우스적 자력구원 배제).
 *    동시에 다윗이 "가만히 있었다" 식의 정적주의(quietism)도 배제 — 그는 나아갔다.
 *  - 다섯 돌 = 다섯 감정(공포/모욕/외로움/신뢰/기도). 감정을 *부정* 하지 않고
 *    하나님 앞에 가지고 나아가는 시편적 정직함(예: 시 13, 22, 62)을 존중한다.
 *  - 외세/거인의 위협이 주제라도 특정 국가·민족 혐오나 정치 선동 금지.
 *    블레셋을 오늘의 어떤 집단으로 치환하지 않는다. 거인은 *개인의 절망* 의 은유다.
 *
 * ─────────────────────────────────────────────────────────────
 * 정신건강 안전선 (lemuel-mental-health-safety) —
 *  - R2 (고난 미화) 금지: "두려움을 견뎌내면 강해진다 / 상처가 너를 키운다" 톤 배제.
 *    두려운 채로 *한 걸음 나아감* 만 다루고, 고통 자체를 의미화·미화하지 않는다.
 *  - R3 (회복 압박) 금지: "믿음으로 두려움을 이겨라" 대신 "떨림을 안고 가도 된다".
 *    승리 결말이라도 사용자의 회복을 재촉하지 않는다.
 *  - R1 (위기): 결말은 소망을 *지금의 상태와 분리* 해 제시하고, 골리앗을 "이겨야 할
 *    과제" 로 던지지 않는다. 다윗의 시편 = *일기* 라는 프레임으로 "솔직한 한 줄"
 *    쓰기(일기 라우팅)로 부드럽게 연결한다. 자해·위기 신호는 홈의 상시 안내
 *    (@/lib/crisis-resources 의 CrisisFooter) 로 커버되며, 본 콘텐츠는 그 위기를
 *    자극하지 않는다.
 */

