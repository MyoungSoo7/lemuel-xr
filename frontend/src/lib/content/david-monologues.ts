/**
 * Scene 4 의 돌 선택 순서에서 *마지막* 감정 id 를 뽑아 결말 키로 변환.
 * order: 사용자가 집은 순서대로의 stone id 배열.
 */
export function lastStoneOf(order: string[]): Scene4LastStone {
  const valid: Scene4LastStone[] = [
    "fear",
    "humiliation",
    "loneliness",
    "trust",
    "prayer",
  ];
  for (let i = order.length - 1; i >= 0; i--) {
    const id = order[i] as Scene4LastStone;
    if (valid.includes(id)) return id;
  }
  return "trust"; // fallback — 신뢰
}
