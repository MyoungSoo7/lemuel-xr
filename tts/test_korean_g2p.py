# 바뀌면 안 되는 것들. 여기 있는 문자열이 바뀌면 규칙이 자기 영역 밖으로 샌 것이다.
UNCHANGED = [
    ("밥 아직", "띄어쓰기를 넘어 연음하지 않는다"),
    ("시편 88편", "숫자·공백은 그대로 둔다"),
    ("XTTS v2 test", "라틴 문자는 그대로 둔다"),
    ("사랑, 기도! 소망?", "문장부호는 그대로 둔다"),
    ("", "빈 문자열"),
]


class KoreanG2PTest(unittest.TestCase):
    def test_발음_규칙표(self):
        for text, expected, rule in CASES:
            with self.subTest(rule=rule, text=text):
                self.assertEqual(to_spoken(text), expected)

    def test_건드리면_안_되는_입력은_한_글자도_안_바뀐다(self):
        for text, why in UNCHANGED:
            with self.subTest(why=why, text=text):
                self.assertEqual(to_spoken(text), text)

    def test_두_번_돌려도_결과가_같다(self):
        """변환은 멱등이어야 한다.

        발음형은 그 자체로 이미 발음형이므로 다시 넣어도 그대로여야 한다. 이게 깨지면
        어딘가에서 규칙이 자기 출력에 또 발동한다는 뜻이고, 캐시 키(발음형 해시)도
        호출 횟수에 따라 달라진다.
        """
        for text, expected, rule in CASES:
            with self.subTest(rule=rule, text=text):
                self.assertEqual(to_spoken(expected), expected)

    def test_한글_음절_전체를_넣어도_한글_음절만_나온다(self):
        """11,172 음절 전수. 조합/분해에서 인덱스가 하나만 어긋나도 여기서 깨진다."""
        all_syllables = "".join(chr(c) for c in range(0xAC00, 0xD7A4))
        out = to_spoken(all_syllables)
        self.assertEqual(len(out), len(all_syllables))
        self.assertTrue(all(0xAC00 <= ord(ch) <= 0xD7A3 for ch in out))


if __name__ == "__main__":
    unittest.main()
